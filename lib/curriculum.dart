String normalizeAnswer(String value) => value
    .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
    .replaceAll(RegExp(r'\s+'), ' ').trim();

String arabicNumber(int n) => '$n'.split('').map((c) => '٠١٢٣٤٥٦٧٨٩'[int.parse(c)]).join();

