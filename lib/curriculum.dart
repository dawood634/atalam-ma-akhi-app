enum ExerciseKind { choice, reading, dictation, blend }

class Lesson {
  final String title, explanation, question, category;
  final List<String> choices, words;
  final int correct;
  final ExerciseKind kind;
  const Lesson(this.title, this.explanation, this.question, this.choices, this.correct,
    {this.category = 'البداية', this.words = const [], this.kind = ExerciseKind.choice});
}

class WordGroup {
  final String title;
  final List<String> words;
  const WordGroup(this.title, this.words);
}

